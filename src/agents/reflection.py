from langchain.agents import create_agent

from src.llm import get_llm
from src.schemas import VerificationResult, ReflectionOutput, DescriptionOutput


SYSTEM_PROMPT = """You are the Reflection Agent in the Spec2RTL-Agent system.

Your task is to analyze the output of the Verification Agent.

You will receive:
- The original hardware specification
- The description generated by the Description Agent
- The verification result

If verification is successful:
- Do not suggest unnecessary corrections.
- Set needs_revision to false.

If verification fails:
- Analyze the issues identified by the Verification Agent.
- Identify what needs to be corrected.
- Provide clear feedback for improving the description.
- Set needs_revision to true when corrections are supported.

Rules:
- Do not generate RTL code.
- Do not invent hardware requirements.
- Base all corrections on the original specification.
- Do not silently resolve ambiguities.
- Return the result strictly according to the ReflectionOutput schema.
"""


def create_reflection_agent():
    return create_agent(
        model=get_llm(),
        tools=[],
        response_format=ReflectionOutput,
        system_prompt=SYSTEM_PROMPT
    )


def reflect_on_verification(
    source_chunks: list,
    description: DescriptionOutput,
    verification: VerificationResult
) -> ReflectionOutput:

    if verification.valid:
        return ReflectionOutput(
            needs_revision=False,
            feedback=[],
            reasoning="Verification passed. No revision required."
        )

    agent = create_reflection_agent()

    specifications = "\n\n".join(
        doc.page_content for doc in source_chunks
    )

    result = agent.invoke(
        {
            "messages": [
                {
                    "role": "user",
                    "content": f"""
                    Original Specification:
                    {specifications}

                    Description:
                    {description.model_dump_json(indent=2)}

                    Verification Result:
                    {verification.model_dump_json(indent=2)}

                    Analyze the verification result and provide feedback.
                    """
                }
            ]
        }
    )

    return result["structured_response"]