from src.schemas import DescriptionOutput
from langchain.agents import create_agent

from src.llm import get_llm
from src.schemas import VerificationResult



SYSTEM_PROMPT = """You are the Verification Agent in the Spec2RTL-Agent system.

Compare the original hardware specification with the description
generated by the Description Agent.

Do not generate or modify descriptions or RTL.

Do not assume behavior that is not stated in the specification.

Check the description for:
- Required module name
- Required input and output signals
- Signal names and widths, wherever specified
- Every explicitly required functional operation
- Reset, clock, and timing behavior, wherever specified
- Missing, incomplete, or contradictory behavior

For VerificationResult:
- Set valid to true only when all explicitly stated requirements
  are represented correctly in the description.
- Set valid to false if any explicitly required operation,
  signal, or behavior is missing or incorrect.
- General descriptions are not sufficient when the specification
  names specific operations.
  For example, if the specification requires addition and AND,
  the description must explicitly mention both.
- Do not treat unspecified widths or behavior as mismatches.
- Put mismatches in issues.
- Suggest relevant simulator tests in suggestions.
- Explain the review scope and evidence in reasoning.
- State that no RTL was supplied and no simulator was run.

The final response must conform strictly to the VerificationResult schema.
"""



def create_verification_agent():
  return create_agent(
    model= get_llm(),
    tools=[],
    response_format = VerificationResult,
    system_prompt = SYSTEM_PROMPT


  )


def verify_description(source_chunks:list,description:DescriptionOutput)-> VerificationResult:
  agent = create_verification_agent()

  specifications = "\n\n".join(doc.page_content for doc in source_chunks)

  

  result = agent.invoke(
    {
      "messages":[
        {
          "role":"user",
          "content":f"""
          Original Specification : 
          {specifications}

          Description to Verify:
          {description.model_dump_json(indent=2)}
          Verify the description against the original specification."""

          
        }
      ]
    }
  )
  return result['structured_response']

